def format_github_comment(comment: str) -> str:
    """Format comments with a professional J-Bot attribution."""

    comment = comment.strip()

    if not comment:
        raise ValueError("Comment cannot be empty.")

    signature = (
        "---\n\n"
        "<sub>🤖 Generated by **J-Bot** · "
        "AI-assisted GitHub maintenance</sub>"
    )

    if "Generated by **J-Bot**" in comment:
        return comment

    return f"{comment}\n\n{signature}"


def close_github_item(
    repository: str, number: int, item_type: str, reason: str, duplicate_of: int = 0
) -> dict:
    """Comment on and close a GitHub issue or PR."""

    try:
        gh = get_github(GIT_TOKEN)
        repo = gh.get_repo(repository)

        if item_type == "issue":
            item = repo.get_issue(number)
        elif item_type == "pull_request":
            item = repo.get_pull(number)
        else:
            return {"success": False, "error": "Invalid item type."}

        if item.state == "closed":
            return {"success": False, "error": f"This {item_type} is already closed."}

        if reason == "duplicate":
            if duplicate_of:
                original = repo.get_issue(duplicate_of)

                message = (
                    f"This is being closed as a duplicate of "
                    f"[#{duplicate_of}]({original.html_url}).\n\n"
                    "Please continue the discussion in the original."
                )
            else:
                message = (
                    "This is being closed as a duplicate. "
                    "Please refer to the existing discussion."
                )

        elif reason == "stale":
            message = (
                "This is being closed as stale due to inactivity. "
                "If this is still relevant, please reopen it "
                "or provide an update."
            )

        else:
            return {"success": False, "error": "Invalid closing reason."}

        formatted = format_github_comment(message)

        # Post explanation first.
        comment = item.create_comment(formatted)

        # Close the issue or PR.
        if item_type == "issue":
            item.edit(state="closed", state_reason="not_planned")
        else:
            item.edit(state="closed")

        return {
            "success": True,
            "action": f"closed_as_{reason}",
            "type": item_type,
            "number": number,
            "comment_url": comment.html_url,
            "url": item.html_url,
        }

    except GithubException as e:
        return {"success": False, "error": str(e)}


def tool(description):
    """
    Register a normal Python function as an AI tool.

    Example:

        @tool("Get the weather")
        def weather(city: str):
            ...
    """

    def decorator(function):

        name = function.__name__

        TOOL_REGISTRY[name] = {
            "function": function,
            "description": description,
        }

        return function

    return decorator


def python_type_to_json(annotation):
    """
    Convert basic Python type annotations into JSON Schema.
    """

    if annotation is str:
        return {"type": "string"}

    if annotation is int:
        return {"type": "integer"}

    if annotation is float:
        return {"type": "number"}

    if annotation is bool:
        return {"type": "boolean"}

    return {"type": "string"}


def generate_tool_schema(name, description, function):
    """
    Automatically generate the OpenAI-compatible tool schema
    from the Python function signature.
    """

    signature = inspect.signature(function)

    properties = {}
    required = []

    for parameter in signature.parameters.values():

        if parameter.kind in (
            parameter.VAR_POSITIONAL,
            parameter.VAR_KEYWORD,
        ):
            continue

        annotation = parameter.annotation

        if annotation is inspect.Parameter.empty:
            annotation = str

        properties[parameter.name] = python_type_to_json(annotation)

        if parameter.default is inspect.Parameter.empty:
            required.append(parameter.name)

    return {
        "type": "function",
        "function": {
            "name": name,
            "description": description,
            "parameters": {
                "type": "object",
                "properties": properties,
                "required": required,
                "additionalProperties": False,
            },
        },
    }


def get_tool_schemas():
    return [
        generate_tool_schema(
            name,
            data["description"],
            data["function"],
        )
        for name, data in TOOL_REGISTRY.items()
    ]


def execute_tool(name, arguments):

    if name not in TOOL_REGISTRY:
        raise ValueError(f"Tool '{name}' is not allowed.")

    function = TOOL_REGISTRY[name]["function"]

    return function(**arguments)


