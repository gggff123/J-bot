@tool("Merge a GitHub pull request")
def github_merge_pr(
    repository: str,
    pr_number: int,
    merge_method: str = "merge",
    commit_message: str = "",
) -> dict:
    """
    Merge a pull request.
    merge_method must be merge, squash, or rebase.
    """
    try:
        if merge_method not in ("merge", "squash", "rebase"):
            return {
                "success": False,
                "error": "Invalid merge method. Use merge, squash, or rebase.",
            }

        gh = get_github(GIT_TOKEN)
        repo = gh.get_repo(repository)
        pr = repo.get_pull(pr_number)

        if pr.merged:
            return {"success": False, "error": "This pull request is already merged."}

        if pr.state != "open":
            return {"success": False, "error": "Cannot merge a closed pull request."}

        result = pr.merge(
            commit_message=commit_message or None, merge_method=merge_method
        )

        return {
            "success": result.merged,
            "merged": result.merged,
            "message": result.message,
            "sha": result.sha,
            "number": pr_number,
            "url": pr.html_url,
        }

    except GithubException as e:
        return {"success": False, "error": str(e)}


